import { createRequire } from 'module'; const puppeteer = createRequire('C:/Users/aleja/Documents/BACO-OBRA/package.json')('puppeteer-core');
const [url, out, wait='15000', w='1600', h='900'] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=d3d11','--enable-webgl','--ignore-gpu-blocklist'] });
const p = await b.newPage(); await p.setViewport({ width: +w, height: +h });
const errs=[]; p.on('pageerror', e => errs.push(e.message));
await p.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
await new Promise(r => setTimeout(r, +wait));
await p.screenshot({ path: out });
console.log('errors:', errs.slice(0,5).join(' | ') || 'none');
await b.close();
